"""Import Instagram cookies from your real browser for yt-dlp.

One-time setup:

1. Install the "Cookie-Editor" extension in your browser — https://cookie-editor.com
2. Visit https://instagram.com — make sure you're signed in.
3. Click the Cookie-Editor toolbar icon.
4. Click "Export" → choose "JSON" → it copies the cookie array to your clipboard.
5. Paste the clipboard contents into a file, e.g.
   ~/projects/reels-digest-agent/data/instagram_cookies.json
6. Run:

    python scripts/import_instagram_cookies.py data/instagram_cookies.json

Writes data/instagram_cookies.txt in Netscape HTTP Cookie File format. yt-dlp
loads it automatically (see src/config.py:INSTAGRAM_COOKIES_FILE). Re-run if
Instagram invalidates the session.
"""

import json
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent
OUT_FILE = BASE_DIR / "data" / "instagram_cookies.txt"


def _to_netscape_line(cookie: dict) -> str | None:
    name = cookie.get("name")
    value = cookie.get("value")
    domain = cookie.get("domain")
    if not name or value is None or not domain:
        return None
    include_subdomains = "TRUE" if not cookie.get("hostOnly", False) else "FALSE"
    path = cookie.get("path", "/")
    secure = "TRUE" if cookie.get("secure", False) else "FALSE"
    exp = cookie.get("expirationDate")
    expires = str(int(float(exp))) if exp is not None else "0"
    domain_field = f"#HttpOnly_{domain}" if cookie.get("httpOnly") else domain
    return "\t".join([domain_field, include_subdomains, path, secure, expires, name, value])


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("Usage: python scripts/import_instagram_cookies.py <cookies.json>", file=sys.stderr)
        return 2
    src = Path(argv[1]).expanduser()
    if not src.is_absolute():
        src = (BASE_DIR / src).resolve()
    if not src.exists():
        print(f"File not found: {src}", file=sys.stderr)
        return 1
    raw = json.loads(src.read_text())
    if not isinstance(raw, list):
        print("Expected a JSON array of cookies (Cookie-Editor JSON export).", file=sys.stderr)
        return 1
    ig_cookies = [c for c in raw if "instagram.com" in str(c.get("domain", "")).lower()]
    lines = [_to_netscape_line(c) for c in ig_cookies]
    lines = [ln for ln in lines if ln]
    if not lines:
        print("No instagram.com cookies found in the export.", file=sys.stderr)
        return 1
    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    header = "# Netscape HTTP Cookie File\n# Generated by scripts/import_instagram_cookies.py\n"
    OUT_FILE.write_text(header + "\n".join(lines) + "\n")
    OUT_FILE.chmod(0o600)
    print(f"Wrote {len(lines)} instagram.com cookies to {OUT_FILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
